// isGeneratedFile 判断文件是否为自动生成的文件
func (a *MRAnalyzer) isGeneratedFile(content string) bool {
	// 检查文件开头的几行是否包含常见的自动生成文件标记
	lines := strings.Split(content, "\n")

	// 只检查前15行，通常自动生成文件的标记都在文件开头
	checkLineCount := 15
	if len(lines) < checkLineCount {
		checkLineCount = len(lines)
	}

	// 常见的自动生成文件的标记
	generatedMarkers := []string{
		"Code generated",
		"DO NOT EDIT",
		"GENERATED",
		"Auto-generated",
		"Automatically generated",
		"This file was auto-generated",
		"This code was generated",
		"generated by",
		"This is a generated file",
		"NOTE: This file is auto generated",
	}

	// 检查前几行是否包含自动生成标记
	for i := 0; i < checkLineCount; i++ {
		for _, marker := range generatedMarkers {
			if strings.Contains(strings.ToUpper(lines[i]), strings.ToUpper(marker)) {
				return true
			}
		}
	}

	// 检查protobuf生成文件的特征
	protoRegex := regexp.MustCompile(`(?i)(proto|grpc)\..*RegisterService`)
	if protoRegex.MatchString(content) {
		return true
	}

	// 检查是否包含特定的生成工具注释
	toolsRegex := regexp.MustCompile(`(?i)generated.*(by|with|using).*\b(protoc|swagger|openapi|grpc|pb|thrift|avro|jooq|gorm|sqlc)\b`)
	return toolsRegex.MatchString(content)
}

// filterFileByName 通过文件名判断是否为自动生成的文件
func (a *MRAnalyzer) filterFileByName(filename string) bool {
	// 检查常见的生成文件命名模式
	patterns := []string{
		`\.pb\.go$`,             // protobuf生成的文件
		`\.gen\.go$`,            // 通用生成文件后缀
		`_gen\.go$`,             // 另一种通用生成文件后缀
		`_generated\.go$`,       // 包含generated的文件
		`mock_.*\.go$`,          // mock文件
		`.*\.generated\.go$`,    // 另一种generated文件格式
		`.*-gen\.go$`,           // 使用连字符的生成文件
		`swagger\.json$`,        // swagger生成文件
		`openapi\.json$`,        // openapi文件
		`.*_string\.go$`,        // stringer生成的文件
		`zz_generated\..*\.go$`, // k8s样式的生成文件
		`.*_test\.go$`,          // 测试文件
	}

	for _, pattern := range patterns {
		matched, _ := regexp.MatchString(pattern, filename)
		if matched {
			return true
		}
	}

	return false
}

func (a *MRAnalyzer) fetchModifiedFile(task fileProcessTask) fileProcessResult {
	if task.Content == "" {
		a.logger.Infof("File %s is empty, skipping", task.Filename)
		return fileProcessResult{
			Filename:   task.Filename,
			ChangeType: task.ChangeType,
		}
	}
	a.logger.Infof("Fetching modified file %s", task.Filename)
	a.Mutex.Lock()
	defer a.Mutex.Unlock()
	result := fileProcessResult{
		Filename:   task.Filename,
		ChangeType: task.ChangeType,
	}

	// 中文注释：为提升准确率，构造“函数级小 diff + 上下文”输入。
	// 1) 从 MR 的 unified diff 作为主证据；
	// 2) 尝试获取 Source 分支上的源码片段，以便模型判断边界/并发/错误处理等上下文。
	input := task.Content
	if task.ProjectID != 0 && task.Path != "" && task.Ref != "" {
		if src, err := a.git.GetRawFile(task.ProjectID, task.Path, task.Ref); err == nil {
			// 限制上下文体量，避免超长：仅截取前后 200 行以内（此处简化为前后若干 KB）。
			// 中文注释：MVP 直接拼接；后续可按函数边界精确截取。
			const maxCtx = 16 * 1024
			ctxSnippet := src
			if len(ctxSnippet) > maxCtx {
				ctxSnippet = ctxSnippet[:maxCtx]
			}
			input = "# Unified Diff\n" + task.Content + "\n\n# Source Context (truncated)\n" + ctxSnippet
		}
	}

	res, err := a.provider.AnalyzeFile(context.Background(), input)
	if err != nil {
		a.logger.Warnf("Failed to analyze file %s: %v", task.Filename, err)
		result.Error = err
		return result
	}
	for _, r := range res {
		result.Functions = append(result.Functions, r)
	}
	return result
}

// fetchAndProcessFile 异步获取并处理文件内容
func (a *MRAnalyzer) fetchAndProcessFile(task fileProcessTask) fileProcessResult {
	a.logger.Infof("Fetching and processing file %s", task.Filename)
	// 如果是Modified, 使用AI进行分析
	if task.ChangeType == dos.Modified {
		return a.fetchModifiedFile(task)
	}

	result := fileProcessResult{
		Filename:   task.Filename,
		ChangeType: task.ChangeType,
	}

	// 非Modified, 获取文件内容
	content, err := a.git.GetRawFile(task.ProjectID, task.Path, task.Ref)

	if err != nil {
		a.logger.Warnf("Failed to get file content for %s file %s: %v", string(task.ChangeType), task.Path, err)
		result.Error = err
		return result
	}

	if a.isGeneratedFile(string(content)) {
		return result
	}

	// Added：使用 LLM 对新增源码进行函数级问题分析（通过合成的 unified diff）
	if task.ChangeType == dos.Added {
		diff := buildAddedUnifiedDiff(task.Filename, string(content))
		if diff != "" {
			lres, lerr := a.provider.AnalyzeFile(context.Background(), diff)
			if lerr == nil {
				for _, r := range lres {
					// 中文注释：新增默认为有效改动
					r.IsValid = true
					if r.Reason == "" {
						r.Reason = "新增函数"
					}
					result.Functions = append(result.Functions, r)
				}
				return result
			}
			a.logger.Warnf("LLM analyze added file failed %s: %v, fallback to AST", task.Filename, lerr)
		}
	}

	// 其他情况（含 Deleted 或 LLM 失败回退）：AST 提取
	functions, err := a.extractFunctions(string(content))
	if err != nil {
		a.logger.Warnf("Failed to extract functions from %s file %s: %v", string(task.ChangeType), task.Path, err)
		result.Error = err
		return result
	}
	for _, fn := range functions {
		switch task.ChangeType {
		case dos.Added:
			fn.IsValid = true
			fn.Reason = "新增函数"
		case dos.Deleted:
			fn.IsValid = false
			fn.Reason = "函数被删除"
			if fn.Suggestion == "" {
				fn.Suggestion = "检查潜在上游破坏性调用"
			}
		}
	}
	result.Functions = functions
	return result
}

